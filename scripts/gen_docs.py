def months(days: int) -> int:
    return round(days / 30.4)


def facts(t: str) -> dict:
    r = Repo(t)
    out = {}
    d = latest_output(r, "pf.app_discovery")
    nf = [f for f in d["findings"] if f["type"] == "new_app"]
    out["shadow"] = len(nf)
    out["shadow_genai_expense"] = sum(1 for f in nf if f.get("genai") and f.get("paid_via_expense"))
    out["genai_names"] = [f["candidate_name"] for f in nf if f.get("genai")]
    out["retired_candidates"] = [g["canonical"] for g in r.all("gt_shadow_it") if g["truth"] == "retired"]
    out["cmdb_dup"] = sum(1 for f in d["findings"] if f["type"] == "cmdb_duplicate")
    out["cmdb_stale"] = sum(1 for f in d["findings"] if f["type"] == "cmdb_stale")
    out["expense_ref"] = (d["findings"] and next((f["source_refs"][0]["record_id"] for f in nf if f.get("paid_via_expense")), ""))
    lc = latest_output(r, "pf.lifecycle_watcher")
    eos = [f for f in lc["findings"] if f["type"] == "vendor_eos"]
    out["eos"] = eos
    traps = [f for f in lc["findings"] if f["type"] == "contract_renewal" and f.get("auto_renew") and (f.get("utilization") or 1) < 0.3]
    out["traps"] = traps
    ov = latest_output(r, "pf.overlap_finder")
    out["overlaps"] = ov["findings"]
    rk = latest_output(r, "dai.ai_risk_classifier")
    out["tiers"] = {f["title"]: f["tier"] for f in rk["findings"]}
    out["tier_counts"] = Counter(f["tier"] for f in rk["findings"])
    reg = latest_output(r, "dai.model_agent_registry_steward")
    out["assets"] = reg["facts"] if "facts" in reg else None
    out["n_assets"] = r.count("ai_assets")
    out["n_unreg"] = sum(1 for a in r.all("ai_assets") if not a["registered"])
    dr = latest_output(r, "app.design_review")
    out["designs"] = {f["title"]: f for f in dr["findings"]}
    dd = latest_output(r, "app.drift_detector")
    out["boundary"] = [f for f in dd["findings"] if f["type"] == "boundary_violation"]
    cost = latest_output(r, "pf.cost_license_optimizer")
    out["cost"] = cost["findings"]
    out["apps"] = {a["name"]: a for a in r.all("applications")}
    out["metrics"] = dashboard(t)
    return out


