def usd(v: float) -> str:
    return f"${v / 1e6:.1f}M" if v >= 1e6 else f"${v / 1e3:.0f}k"


def data_readme() -> str:
    from data_gen.generators.core import load_yaml  # noqa: F401

    lines = ["# Synthetic data generator", "", "```", "python -m data_gen.generate --tenant northgrid --seed 42 --out data/northgrid.db",
             "python -m data_gen.generate --tenant meridian --seed 42 --out data/meridian.db", "python -m data_gen.generate --all", "```", "",
             "Deterministic: same seed + same `DEMO_TODAY` → identical data. All dates are relative to `DEMO_TODAY` (default today).",
             "Industry content is hand-authored in `catalogs/utilities.yaml`, `catalogs/telecom.yaml`, `catalogs/common.yaml` and",
             "`catalogs/ai_risk_rules.yaml`; generators in `generators/` add the long tail and the planted anomalies.",
             "Raw per-source exports (`sso.csv`, `invoices.csv`, `cmdb.json`, `cloud.json`, `repos.json`, `catalog.json`, …) are written",
             "to `data/{tenant}/raw/`. After writing the tables the generator builds the knowledge graph and runs every agent once",
             "(baseline, trigger `scheduled`) plus a small set of historical decisions (`backend/app/services/bootstrap.py`).", "",
             "## Tables and volumes", "", "| Table | NorthGrid | Meridian | Notes |", "|---|---|---|---|"]
    notes = {"gt_app_aliases": "hidden ground truth: raw name → application", "gt_shadow_it": "hidden ground truth: shadow IT",
             "gt_planted": "hidden ground truth: every planted anomaly", "kg_nodes": "knowledge graph", "kg_edges": "knowledge graph",
             "agent_runs": "baseline runs", "approvals": "baseline proposals + history", "audit_events": "", "tickets": "simulated Jira"}
    rn, rm = Repo("northgrid"), Repo("meridian")
    for t in models.metadata.tables:
        if t in ("tenants", "meta_kv", "agent_settings"):
            continue
        lines.append(f"| `{t}` | {rn.count(t)} | {rm.count(t)} | {notes.get(t, '')} |")
    lines += ["", "## Planted anomalies (counts)", "", "| Anomaly | NorthGrid | Meridian |", "|---|---|---|"]
    cn = Counter(p["anomaly"] for p in rn.all("gt_planted"))
    cm = Counter(p["anomaly"] for p in rm.all("gt_planted"))
    for k in sorted(set(cn) | set(cm)):
        lines.append(f"| {k.replace('_', ' ')} | {cn.get(k, 0)} | {cm.get(k, 0)} |")
    lines += ["", "Every planted anomaly is listed with its subject record in table `gt_planted` and shown in the UI under",
              "**Ingested Sources → show what we planted**. Tests in `backend/tests/test_planted_anomalies.py` assert the ranges."]
    return "\n".join(lines) + "\n"


def gen_prompts(overwrite: bool = False) -> int:
    """Live-mode prompt per agent: role, inputs, finding schema, rules (+ shared rules from _common.md)."""
    import json

    from app.agents.registry import AGENTS

    pdir = ROOT / "backend" / "app" / "llm" / "prompts"
    common = (pdir / "_common.md").read_text()
    n = 0
    for a in AGENTS.values():
        path = pdir / f"{a.id}.md"
        if not a.runnable or (path.exists() and not overwrite):
            continue
        props = {k: v.get("type", v.get("anyOf", "")) for k, v in a.finding_model.model_json_schema().get("properties", {}).items()}
        path.write_text(
            f"# {a.name} (`{a.id}`)\n\n## Role\n{a.description}\n\n## Inputs\nTables read by the tool layer: {', '.join(a.inputs)}. "
            f"The user message contains the tool results as JSON: `facts` and `findings` (typed `{a.outputs}`, each with `source_refs`).\n\n"
            f"## Finding schema (already computed — do not change values)\n```json\n{json.dumps(props, indent=1, default=str)}\n```\n\n"
            f"## What to write\n- A summary a {a.approver_role or 'principal architect'} can act on, leading with the most material finding.\n"
            f"- Rank findings by business impact (risk, money, deadline) in `order`.\n"
            f"- Optionally add up to 5 `notes`, each citing that finding's record ids.\n"
            f"- Proposed actions ({', '.join(a.action_types) or 'none'}) are created by the platform; never claim anything is approved.\n\n{common}")
        n += 1
    return n


def main() -> None:
    gen_prompts()
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "AGENT_CATALOG.md").write_text(catalog_markdown())
    (ROOT / "docs" / "DEMO_SCRIPT.md").write_text(demo_script())
    (ROOT / "data_gen" / "README.md").write_text(data_readme())
    print("wrote docs/AGENT_CATALOG.md, docs/DEMO_SCRIPT.md, data_gen/README.md")


if __name__ == "__main__":
    main()
